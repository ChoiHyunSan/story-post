import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { serializeMigrationLock, validateMigrationLock } from './migration-lock';
const files = readdirSync('src/storage/migrations').filter(file => file.endsWith('.sql')).sort();
const migrations = files.map((file, index) => {
  if (!/^\d{3}_[a-z0-9-]+\.sql$/.test(file)) throw new Error(`Invalid migration filename: ${file}`);
  if (Number(file.slice(0, 3)) !== index + 1) throw new Error('Migration versions must be sequential');
  return { version: index + 1, sql: readFileSync(`src/storage/migrations/${file}`, 'utf8') };
});
const hashes = Object.fromEntries(files.map(file => [file,
  createHash('sha256').update(readFileSync(`src/storage/migrations/${file}`)).digest('hex')]));
const lockPath = 'src/storage/migrations.lock.json';
if (existsSync(lockPath)) validateMigrationLock(hashes, JSON.parse(readFileSync(lockPath, 'utf8')) as unknown);
const lockOutput = serializeMigrationLock(hashes);
const output = '// Generated by pnpm db:build. Edit migration SQL, not this file.\n' +
  'export const migrations = ' + JSON.stringify(migrations, null, 2) + ' as const;\n';
const path = 'src/generated/migrations.ts';
if (process.argv.includes('--check')) {
  if (!existsSync(lockPath) || readFileSync(lockPath, 'utf8') !== lockOutput) {
    throw new Error('Run pnpm db:build to register migrations');
  }
  if (readFileSync(path, 'utf8') !== output) throw new Error('Run pnpm db:build');
} else {
  writeFileSync(lockPath, lockOutput);
  writeFileSync(path, output);
}
const design = readFileSync('design/schema.sql', 'utf8');
const designVersion = Number(design.match(/PRAGMA user_version\s*=\s*(\d+)\s*;/)?.[1] ?? -1);
if (designVersion !== migrations.length) throw new Error('Current design schema version does not match migrations');
console.log(`Verified ${migrations.length} migration(s)`);
